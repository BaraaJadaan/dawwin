let UI_LANG = "en";

/** The string for `key` in the interface language, with `{name}` filled from `vars`. */
function t(key, vars = {}) {
  const pack = I18N[UI_LANG] || I18N.en;
  let s = pack.s[key] ?? I18N.en.s[key] ?? key;
  if (typeof s === "object") {
    const cat = new Intl.PluralRules(pack.locale).select(vars.n ?? 0);
    s = s[cat] ?? s.other;
  }
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Like t(), as HTML: the string is ours; variables are escaped, or inserted as given when
 *  wrapped with raw() (e.g. a left-to-right path inside Arabic text). */
function tHtml(key, vars = {}) {
  const pack = I18N[UI_LANG] || I18N.en;
  let s = pack.s[key] ?? I18N.en.s[key] ?? key;
  if (typeof s === "object") s = s[new Intl.PluralRules(pack.locale).select(vars.n ?? 0)] ?? s.other;
  const e = (x) => String(x).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? (vars[k]?.raw ?? e(vars[k])) : m));
}
const raw = (html) => ({ raw: html });
/** Text that reads left to right (a path, a command) inside a sentence of either direction. */
const ltr = (text) => raw(`<bdi dir="ltr">${String(text).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]))}</bdi>`);

/** Fill the static page: data-i18n (text), data-i18n-ph (placeholder), data-i18n-aria (label). */
function applyI18n() {
  const pack = I18N[UI_LANG] || I18N.en;
  document.documentElement.lang = UI_LANG;
  document.documentElement.dir = pack.dir;
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  document.title = t("app.name");
}
